import { useEffect, useRef } from "react";

/** Adds the `visible` class when the element scrolls into view. */
export function Reveal({ children, className = "", delay = 0, as: Tag = "div" }) {
  const ref = useRef(null);
  useEffect(() => {
    const el = ref.current;
    const io = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) {
          el.classList.add("visible");
          io.disconnect();
        }
      },
      { threshold: 0.12 }
    );
    io.observe(el);
    return () => io.disconnect();
  }, []);
  return (
    <Tag ref={ref} className={`reveal ${className}`} style={{ transitionDelay: `${delay}ms` }}>
      {children}
    </Tag>
  );
}

export function Section({ id, eyebrow, title, children }) {
  return (
    <section id={id} className="relative mx-auto max-w-6xl px-6 py-24">
      <Reveal className="mb-14">
        <p className="font-mono text-sm tracking-widest text-violet-400 uppercase">{eyebrow}</p>
        <h2 className="mt-2 text-3xl font-bold text-white sm:text-4xl">{title}</h2>
        <div className="mt-4 h-1 w-20 rounded-full bg-gradient-to-r from-violet-500 to-cyan-400" />
      </Reveal>
      {children}
    </section>
  );
}

/** Renders **bold** segments from a plain string. */
export function Rich({ text }) {
  return text.split(/(\*\*[^*]+\*\*)/g).map((part, i) =>
    part.startsWith("**") ? (
      <strong key={i} className="font-semibold text-white">
        {part.slice(2, -2)}
      </strong>
    ) : (
      <span key={i}>{part}</span>
    )
  );
}

export function Tag({ children }) {
  return (
    <span className="rounded-full border border-white/10 bg-white/5 px-3 py-1 font-mono text-xs text-slate-300">
      {children}
    </span>
  );
}

export function LinkButton({ href, children, icon }) {
  return (
    <a
      href={href}
      target="_blank"
      rel="noreferrer"
      className="inline-flex items-center gap-1.5 rounded-lg border border-white/10 bg-white/5 px-3 py-1.5 text-sm font-medium text-slate-200 transition hover:border-violet-400/60 hover:bg-violet-500/10 hover:text-white"
    >
      {icon}
      {children}
    </a>
  );
}

